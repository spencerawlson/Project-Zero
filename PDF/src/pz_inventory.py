def roblox_name(a):
    """PZ_<District>_<Asset>_<Variant> — the convention already set in the Asset Reference Bible p.14."""
    return "PZ_%s_%s_A" % (a[2], "".join(w for w in a[1].replace("-", " ").title().split() if w.isalnum() or w.replace("-", "").isalnum()))

def status(a):
    if a[0].startswith("CHR"):
        return "SHEET %s" % a[0]
    return "SF-01–05 (approved)" if a[0] == "BLD-01" else ("in BLD-01 package" if a[0] == "INT-01" else "sheet Rev D")
